// ---------------------------------------------------------------------------
// Own QR preview — fetches own identity and renders QRCanvas
// ---------------------------------------------------------------------------
function OwnQRPreview() {
  const [identity, setIdentity] = useState(null)
  const [error, setError]       = useState(null)

  useEffect(() => {
    fetch('/api/peering/identity')
      .then(r => r.ok ? r.json() : Promise.reject(new Error(`${r.status}`)))
      .then(data => setIdentity(data))
      .catch(err => setError(err.message))
  }, [])

  if (error) {
    return <p className="text-xs text-red-400">Could not load identity: {error}</p>
  }
  if (!identity) {
    return (
      <div className="flex justify-center py-4">
        <span className="w-4 h-4 border-2 border-neutral-700 border-t-indigo-500 rounded-full animate-spin" />
      </div>
    )
  }

  const vulaId = identity.vula_id || ''
  if (!vulaId) return <p className="text-xs text-neutral-600">No Vula ID found.</p>

  return (
    <div className="flex flex-col items-center gap-3 p-4 rounded-xl bg-neutral-900/60 border border-neutral-800/40">
      <div className="rounded-xl overflow-hidden p-2 bg-neutral-900 border border-neutral-800">
        <QRCanvas value={vulaId} size={160} darkColor="#ffffff" lightColor="#111827" />
      </div>
      <p className="text-[10px] text-neutral-700 font-mono break-all text-center max-w-xs">{vulaId}</p>
    </div>
  )
}
