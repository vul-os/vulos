// ---------------------------------------------------------------------------
// Vula ID validation
// Format: vula:ed25519:<base58-encoded-public-key>[@host:port]
// Also accept bare domain slugs like alice.vulos.org for domain-based discovery.
// ---------------------------------------------------------------------------
const VULA_ID_RE = /^vula:ed25519:[1-9A-HJ-NP-Za-km-z]{32,}(@[\w.-]+(:\d+)?)?$/

function validateVulaAddress(raw) {
  const trimmed = raw.trim()
  if (!trimmed) return { ok: false, error: 'Enter a Vula address.' }

  // Accept vula:ed25519:... with optional @host
  if (VULA_ID_RE.test(trimmed)) return { ok: true, value: trimmed }

  // Accept domain slugs: alice.vulos.org or alice.vulos.org:8080
  if (/^[\w-]+(\.[\w-]+)+(:\d+)?$/.test(trimmed)) return { ok: true, value: trimmed }

  // Reject anything else with a helpful message
  if (trimmed.startsWith('vula:') && !trimmed.startsWith('vula:ed25519:')) {
    return { ok: false, error: 'Unrecognised key type — expected vula:ed25519:…' }
  }
  if (trimmed.startsWith('vula:ed25519:') && trimmed.length < 28) {
    return { ok: false, error: 'Key too short — check you pasted the full Vula ID.' }
  }
  return {
    ok: false,
    error:
      'Not a valid Vula address. Expected "vula:ed25519:<key>[@host:port]" or a domain slug like "alice.vulos.org".',
  }
}

// ---------------------------------------------------------------------------
// POST contact request
// ---------------------------------------------------------------------------
async function sendContactRequest(vulaAddress, message) {
  const res = await fetch('/api/peering/contacts/request', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      vula_id: vulaAddress,
      message: message.trim() || undefined,
    }),
  })
  if (!res.ok) {
    const text = await res.text().catch(() => '')
    throw new Error(`${res.status} ${text || res.statusText}`)
  }
  return res.json().catch(() => ({}))
}

