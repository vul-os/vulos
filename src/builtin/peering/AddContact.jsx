// ---------------------------------------------------------------------------
// Scan tab — camera viewfinder + QR decode loop
// ---------------------------------------------------------------------------
function ScanTab({ onDetected }) {
  const videoRef  = useRef(null)
  const canvasRef = useRef(null)
  const streamRef = useRef(null)
  const rafRef    = useRef(null)
  const foundRef  = useRef(false)
  const tickRef   = useRef(null)

  const [camError, setCamError] = useState(null)
  const [scanning, setScanning] = useState(false)
  const [hint, setHint]     = useState('Starting camera…')

  const stopStream = useCallback(() => {
    if (rafRef.current) { cancelAnimationFrame(rafRef.current); rafRef.current = null }
    if (streamRef.current) {
      streamRef.current.getTracks().forEach(t => t.stop())
      streamRef.current = null
    }
  }, [])

  const tick = useCallback(() => {
    const video  = videoRef.current
    const canvas = canvasRef.current
    if (!video || !canvas || foundRef.current) return

    if (video.readyState < 2) {
      rafRef.current = requestAnimationFrame(tickRef.current)
      return
    }

    const vw = video.videoWidth  || 320
    const vh = video.videoHeight || 240
    canvas.width  = vw
    canvas.height = vh
    const ctx = canvas.getContext('2d')
    ctx.drawImage(video, 0, 0, vw, vh)

    const imgData = ctx.getImageData(0, 0, vw, vh).data
    const bin = thresholdImage(imgData, vw, vh)
    const text = decodeQRBitmap(bin, vw, vh)

    if (text) {
      const result = validateVulaAddress(text)
      if (result.ok) {
        foundRef.current = true
        setHint('QR code detected!')
        stopStream()
        onDetected(result.value)
        return
      }
    }

    rafRef.current = requestAnimationFrame(tickRef.current)
  }, [onDetected, stopStream])

  useEffect(() => {
    tickRef.current = tick
  }, [tick])

  useEffect(() => {
    let mounted = true
    foundRef.current = false

    navigator.mediaDevices
      .getUserMedia({ video: { facingMode: 'environment' }, audio: false })
      .then(stream => {
        if (!mounted) { stream.getTracks().forEach(t => t.stop()); return }
        streamRef.current = stream
        if (videoRef.current) {
          videoRef.current.srcObject = stream
          videoRef.current.play().catch(() => {})
        }
        setScanning(true)
        setHint('Point camera at a Vula QR code…')
        rafRef.current = requestAnimationFrame(tickRef.current)
      })
      .catch(err => {
        if (!mounted) return
        setCamError(
          err.name === 'NotAllowedError'
            ? 'Camera permission denied. Allow camera access and try again.'
            : err.name === 'NotFoundError'
            ? 'No camera found on this device.'
            : `Camera error: ${err.message}`
        )
      })

    return () => {
      mounted = false
      stopStream()
    }
  }, [tick, stopStream])

  if (camError) {
    return (
      <div className="flex flex-col items-center justify-center gap-3 py-10 text-center">
        <svg viewBox="0 0 24 24" className="w-10 h-10 text-red-400/60" fill="currentColor">
          <path d="M12 7c.55 0 1 .45 1 1v4c0 .55-.45 1-1 1s-1-.45-1-1V8c0-.55.45-1 1-1zm0 8c-.55 0-1 .45-1 1s.45 1 1 1 1-.45 1-1-.45-1-1-1zM1 21h22L12 2 1 21z"/>
        </svg>
        <p className="text-sm text-red-400">{camError}</p>
        <p className="text-xs text-neutral-600">Use the Paste tab to enter the Vula address manually.</p>
      </div>
    )
  }

  return (
    <div className="flex flex-col items-center gap-4">
      {/* Viewfinder */}
      <div className="relative w-full max-w-xs aspect-square rounded-2xl overflow-hidden bg-neutral-950 border border-neutral-800/60">
        <video
          ref={videoRef}
          className="w-full h-full object-cover"
          playsInline
          muted
        />
        {/* Corner brackets overlay */}
        <div className="absolute inset-0 pointer-events-none">
          {['top-3 left-3', 'top-3 right-3 rotate-90', 'bottom-3 right-3 rotate-180', 'bottom-3 left-3 -rotate-90'].map((pos, i) => (
            <div key={i} className={`absolute ${pos}`}>
              <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="rgba(99,102,241,0.9)" strokeWidth="3" strokeLinecap="round">
                <path d="M2 12V2h10" />
              </svg>
            </div>
          ))}
        </div>
        {/* Scanning line animation */}
        {scanning && (
          <div className="absolute inset-x-4 h-0.5 bg-indigo-400/70 rounded-full shadow-[0_0_8px_2px_rgba(99,102,241,0.6)] animate-scan-line" />
        )}
        {/* Hidden canvas for frame processing */}
        <canvas ref={canvasRef} className="hidden" />
      </div>

      <p className="text-xs text-neutral-500 text-center">{hint}</p>

      <style>{`
        @keyframes scan-line {
          0%   { top: 12%; }
          50%  { top: 85%; }
          100% { top: 12%; }
        }
        .animate-scan-line { animation: scan-line 2s ease-in-out infinite; position: absolute; }
      `}</style>
    </div>
  )
}

