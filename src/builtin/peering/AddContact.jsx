// Inline QR decoder — reads pixel data from a <canvas> after the user
// captures a video frame via getUserMedia. Uses a simple threshold scan
// sufficient for well-lit QR codes at modest zoom.
// ---------------------------------------------------------------------------

// Decode a QR module grid to a byte string by scanning bit positions.
// This is a compact finder-pattern locator + data extractor.
// For production use replace with a library like jsQR (npm); this covers
// the common Vula ID QR codes generated by QRCanvas.jsx (V1-10, ECC M, mask 0).

function thresholdImage(imgData, w, h) {
  const gray = new Uint8Array(w * h)
  for (let i = 0; i < w * h; i++) {
    const r = imgData[i * 4], g = imgData[i * 4 + 1], b = imgData[i * 4 + 2]
    gray[i] = Math.round(0.299 * r + 0.587 * g + 0.114 * b)
  }
  // Adaptive threshold: Otsu's method
  let sum = 0
  for (let i = 0; i < gray.length; i++) sum += gray[i]
  const mean = sum / gray.length
  let varBetween = 0, bestT = mean
  for (let t = 0; t < 256; t++) {
    let n0 = 0, s0 = 0
    for (let i = 0; i < gray.length; i++) {
      if (gray[i] < t) { n0++; s0 += gray[i] }
    }
    const n1 = gray.length - n0
    if (n0 === 0 || n1 === 0) continue
    const m0 = s0 / n0, m1 = (sum - s0) / n1
    const v = (n0 * n1 * (m0 - m1) ** 2) / (gray.length ** 2)
    if (v > varBetween) { varBetween = v; bestT = t }
  }
  const bin = new Uint8Array(w * h)
  for (let i = 0; i < gray.length; i++) bin[i] = gray[i] < bestT ? 1 : 0
  return bin
}

function locateFinder(bin, w, h) {
  // Find rows with a run matching the 1:1:3:1:1 finder ratio
  const candidates = []
  for (let y = 0; y < h; y++) {
    let runs = [], start = 0, cur = bin[y * w]
    for (let x = 1; x < w; x++) {
      if (bin[y * w + x] !== cur) { runs.push(x - start); start = x; cur = bin[y * w + x] }
    }
    runs.push(w - start)
    // Look for runs of ratio 1:1:3:1:1
    for (let i = 0; i + 4 < runs.length; i++) {
      const r = runs.slice(i, i + 5)
      const u = r[0]
      if (u < 1) continue
      if (
        Math.abs(r[1] - u) <= u * 0.5 &&
        Math.abs(r[2] - 3 * u) <= u * 1.0 &&
        Math.abs(r[3] - u) <= u * 0.5 &&
        Math.abs(r[4] - u) <= u * 0.5
      ) {
        const cx = runs.slice(0, i).reduce((a, b) => a + b, 0) + r[0] + r[1] + Math.round(r[2] / 2)
        candidates.push({ y, x: cx, mod: u })
      }
    }
  }
  return candidates
}

// Attempt a quick decode: locate top-left finder, estimate module size,
// sample the full matrix, decode byte-mode data. Returns string or null.
function decodeQRBitmap(bin, w, h) {
  const candidates = locateFinder(bin, w, h)
  if (candidates.length < 3) return null

  // Sort by y, take top candidates
  candidates.sort((a, b) => a.y - b.y)
  const top = candidates[0]
  const modSize = Math.max(1, top.mod)

  // Estimate version and matrix size
  // Finder pattern is 7 modules; top-left finder top-left corner estimate:
  const tlX = top.x - Math.round(3.5 * modSize)
  const tlY = top.y - Math.round(3 * modSize)
  if (tlX < 0 || tlY < 0) return null

  // Try versions 1-10
  for (let ver = 1; ver <= 10; ver++) {
    const size = ver * 4 + 17
    const mat = []
    for (let r = 0; r < size; r++) {
      const row = []
      for (let c = 0; c < size; c++) {
        const px = Math.round(tlX + c * modSize)
        const py = Math.round(tlY + r * modSize)
        if (px >= 0 && px < w && py >= 0 && py < h) {
          row.push(bin[py * w + px])
        } else {
          row.push(0)
        }
      }
      mat.push(row)
    }
    const text = tryDecodeMatrix(mat, ver)
    if (text) return text
  }
  return null
}

// Minimal byte-mode QR decoder for mask 0 (as produced by QRCanvas.jsx).
function tryDecodeMatrix(mat, ver) {
  try {
    const size = mat.length
    // Un-apply mask 0: (r+c)%2===0 → flip, excluding function modules
    function isFn(r, c) {
      if (r < 9 && c < 9) return true
      if (r < 9 && c >= size - 8) return true
      if (r >= size - 8 && c < 9) return true
      if (r === 6 || c === 6) return true
      if (r === size - 8 && c === 8) return true
      return false
    }
    const m = mat.map((row, r) =>
      row.map((v, c) => {
        if (isFn(r, c)) return v
        return (r + c) % 2 === 0 ? v ^ 1 : v
      })
    )

    // Read data bits in QR zigzag order
    const bits = []
    let goingUp = true
    let col = size - 1
    while (col > 0) {
      if (col === 6) col--
      for (let rowStep = 0; rowStep < size; rowStep++) {
        const row = goingUp ? size - 1 - rowStep : rowStep
        for (let dc = 0; dc <= 1; dc++) {
          const c = col - dc
          if (!isFn(row, c)) bits.push(m[row][c])
        }
      }
      goingUp = !goingUp
      col -= 2
    }

    // Decode byte mode
    let pos = 0
    const readBits = (n) => {
      let v = 0
      for (let i = 0; i < n; i++) v = (v << 1) | (bits[pos++] || 0)
      return v
    }
    const mode = readBits(4)
    if (mode !== 0b0100) return null // not byte mode

    const ccBits = ver <= 9 ? 8 : 16
    const len = readBits(ccBits)
    if (len < 1 || len > 500) return null

    const bytes = []
    for (let i = 0; i < len; i++) bytes.push(readBits(8))

    return new TextDecoder().decode(new Uint8Array(bytes))
  } catch {
    return null
  }
}

